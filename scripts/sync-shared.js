#!/usr/bin/env node

// Injects the shared protocol blocks from shared/ into every skill's SKILL.md.
// Each skill must stay self-contained (skills can be installed one at a time),
// so the shared text is copied into each file between marker comments.
//
//   node scripts/sync-shared.js          # update files in place
//   node scripts/sync-shared.js --check  # exit 1 if any file is out of date

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SKILLS_DIR = path.join(ROOT, 'skills');
const SHARED_DIR = path.join(ROOT, 'shared');

// Skills that orchestrate or manage context rather than produce a deliverable
const EXCLUDED = ['founder', 'founder-context'];

const HOOK_ANCHOR = '**Check $ARGUMENTS first to determine execution mode:**';
const NOTICE = '(generated by scripts/sync-shared.js, edit shared/ instead)';

// Files copied verbatim into a skill's references so it works when installed alone
const COPIES = [
  {
    from: path.join(ROOT, 'FOUNDER_CONTEXT.md'),
    to: path.join(SKILLS_DIR, 'founder-context', 'references', 'founder_context_template.md')
  }
];

function block(name, body) {
  return `<!-- founder-skills:${name}:start ${NOTICE} -->\n${body.trim()}\n<!-- founder-skills:${name}:end -->`;
}

// Replace an existing marked block, or return null if the markers are absent
function replaceBlock(content, name, replacement) {
  const re = new RegExp(`<!-- founder-skills:${name}:start[^>]*-->[\\s\\S]*?<!-- founder-skills:${name}:end -->`);
  // Function replacer so "$&", "$'" etc. in shared text are inserted literally
  return re.test(content) ? content.replace(re, () => replacement) : null;
}

function syncSkill(skill, hookBody, protocolsBody) {
  const file = path.join(SKILLS_DIR, skill, 'SKILL.md');
  const original = fs.readFileSync(file, 'utf8');
  const hook = block('orchestrated-mode', hookBody);
  const protocols = block('protocols', protocolsBody.replace(/\{\{skill\}\}/g, skill));

  let content = replaceBlock(original, 'orchestrated-mode', hook);
  if (content === null) {
    const idx = original.indexOf(HOOK_ANCHOR);
    if (idx === -1) {
      throw new Error(`${skill}: anchor "${HOOK_ANCHOR}" not found`);
    }
    const insertAt = idx + HOOK_ANCHOR.length;
    content = `${original.slice(0, insertAt)}\n\n${hook}${original.slice(insertAt)}`;
  }

  const withProtocols = replaceBlock(content, 'protocols', protocols);
  if (withProtocols !== null) {
    content = withProtocols;
  } else {
    const trimmed = content.trimEnd().replace(/\n---$/, '').trimEnd();
    content = `${trimmed}\n\n---\n\n${protocols}\n`;
  }

  return { file, original, content };
}

function main() {
  const check = process.argv.includes('--check');
  const hookBody = fs.readFileSync(path.join(SHARED_DIR, 'orchestrated-mode-hook.md'), 'utf8');
  const protocolsBody = fs.readFileSync(path.join(SHARED_DIR, 'skill-protocols.md'), 'utf8');

  const skills = fs.readdirSync(SKILLS_DIR).filter(name =>
    !EXCLUDED.includes(name) && fs.existsSync(path.join(SKILLS_DIR, name, 'SKILL.md'))
  );

  const stale = [];

  skills.forEach(skill => {
    const { file, original, content } = syncSkill(skill, hookBody, protocolsBody);
    if (content !== original) {
      stale.push(path.relative(ROOT, file));
      if (!check) fs.writeFileSync(file, content);
    }
  });

  COPIES.forEach(({ from, to }) => {
    const source = fs.readFileSync(from, 'utf8');
    const current = fs.existsSync(to) ? fs.readFileSync(to, 'utf8') : null;
    if (current !== source) {
      stale.push(path.relative(ROOT, to));
      if (!check) {
        fs.mkdirSync(path.dirname(to), { recursive: true });
        fs.writeFileSync(to, source);
      }
    }
  });

  if (check) {
    if (stale.length > 0) {
      console.log(`Out of date (run: node scripts/sync-shared.js):\n  ${stale.join('\n  ')}`);
      process.exit(1);
    }
    console.log(`All ${skills.length} skills in sync.`);
    return;
  }

  console.log(stale.length > 0 ? `Updated:\n  ${stale.join('\n  ')}` : 'Nothing to update.');
}

main();
